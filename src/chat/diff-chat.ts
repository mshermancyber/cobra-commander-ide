import { randomUUID } from 'node:crypto';

// ──────────────────────────────────────────────
// Types
// ──────────────────────────────────────────────

export interface DiffHunk {
  id: string;
  header: string;          // e.g., "@@ -10,7 +10,8 @@"
  oldStart: number;
  oldCount: number;
  newStart: number;
  newCount: number;
  lines: DiffLine[];
}

export interface DiffLine {
  type: 'context' | 'added' | 'removed';
  content: string;
  oldLineNumber?: number;
  newLineNumber?: number;
  /** 0-based index within the hunk */
  hunkIndex: number;
}

export interface ParsedDiff {
  file: string;
  originalFile: string;
  modifiedFile: string;
  hunks: DiffHunk[];
}

export interface LineAnnotation {
  id: string;
  file: string;
  hunkId: string;
  /** Line number in the *new* file that this annotation anchors to */
  anchorLine: number;
  /** The comment thread attached to this line */
  threadId: string;
}

export interface ChatThread {
  id: string;
  hunkId: string;
  file: string;
  /** Line range this thread is about (new file lines) */
  lineRange: { start: number; end: number };
  messages: ChatMessage[];
  resolved: boolean;
  createdAt: number;
  updatedAt: number;
}

export interface ChatMessage {
  id: string;
  threadId: string;
  author: string;
  body: string;
  timestamp: number;
  /** Whether this message was generated by the AI */
  isAi: boolean;
  /** Optional parent message for threading */
  parentId?: string;
}

export interface InlineReply {
  threadId: string;
  hunkId: string;
  file: string;
  anchorLine: number;
  replyText: string;
  /** Rendered HTML/markdown suitable for inline display */
  renderedHtml: string;
}

export interface DiffChatSession {
  id: string;
  diff: ParsedDiff;
  threads: ChatThread[];
  annotations: LineAnnotation[];
  createdAt: number;
}

// ──────────────────────────────────────────────
// Unified Diff Parser
// ──────────────────────────────────────────────

/**
 * Parse a unified diff string into structured hunks with line-level detail.
 * Handles standard `diff -u` / `git diff` output.
 */
export function parseUnifiedDiff(diffOutput: string): ParsedDiff[] {
  if (!diffOutput) return [];

  const results: ParsedDiff[] = [];
  const lines = diffOutput.split('\n');

  let currentFile: ParsedDiff | null = null;
  let currentHunk: DiffHunk | null = null;
  let hunkLineIndex = 0;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    // Match file header: diff --git a/path b/path
    const fileMatch = line.match(/^diff --git a\/(.+?) b\/(.+)/);
    if (fileMatch) {
      if (currentHunk && currentFile) {
        currentFile.hunks.push(currentHunk);
        currentHunk = null;
      }
      if (currentFile) results.push(currentFile);

      currentFile = {
        file: fileMatch[2],
        originalFile: fileMatch[1],
        modifiedFile: fileMatch[2],
        hunks: [],
      };
      hunkLineIndex = 0;
      continue;
    }

    // Match new file mode
    if (line.startsWith('new file mode') || line.startsWith('old mode') || line.startsWith('new mode')) {
      continue;
    }

    // Match index line
    if (line.startsWith('index ')) continue;

    // Match --- / +++ lines
    if (line.startsWith('--- ') || line.startsWith('+++ ')) continue;

    // Match hunk header: @@ -oldStart,oldCount +newStart,newCount @@
    const hunkMatch = line.match(/^@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@(.*)$/);
    if (hunkMatch && currentFile) {
      if (currentHunk) {
        currentFile.hunks.push(currentHunk);
      }
      const oldStart = parseInt(hunkMatch[1], 10);
      const oldCount = parseInt(hunkMatch[2] ?? '1', 10);
      const newStart = parseInt(hunkMatch[3], 10);
      const newCount = parseInt(hunkMatch[4] ?? '1', 10);

      currentHunk = {
        id: `hunk_${randomUUID().slice(0, 8)}`,
        header: line,
        oldStart,
        oldCount,
        newStart,
        newCount,
        lines: [],
      };
      hunkLineIndex = 0;
      continue;
    }

    // Parse hunk body lines
    if (currentHunk) {
      let lineType: DiffLine['type'] = 'context';
      let oldLn: number | undefined;
      let newLn: number | undefined;

      if (line.startsWith('+')) {
        lineType = 'added';
        newLn = currentHunk.newStart + hunkLineIndex;
      } else if (line.startsWith('-')) {
        lineType = 'removed';
        oldLn = currentHunk.oldStart + hunkLineIndex;
      } else if (line.startsWith(' ') || line === '') {
        lineType = 'context';
        oldLn = currentHunk.oldStart + hunkLineIndex;
        newLn = currentHunk.newStart + hunkLineIndex;
      } else {
        // Skip non-diff lines (e.g., "\ No newline at end of file")
        continue;
      }

      currentHunk.lines.push({
        type: lineType,
        content: line.substring(1),
        oldLineNumber: oldLn,
        newLineNumber: newLn,
        hunkIndex: hunkLineIndex,
      });
      hunkLineIndex++;
    }
  }

  // Flush last hunk and file
  if (currentHunk && currentFile) {
    currentFile.hunks.push(currentHunk);
  }
  if (currentFile) results.push(currentFile);

  return results;
}

// ──────────────────────────────────────────────
// Diff Chat Manager
// ──────────────────────────────────────────────

export class DiffChatManager {
  private sessions: Map<string, DiffChatSession> = new Map();

  /**
   * Create a new diff chat session from a parsed diff.
   */
  createSession(diff: ParsedDiff): DiffChatSession {
    const session: DiffChatSession = {
      id: randomUUID(),
      diff,
      threads: [],
      annotations: [],
      createdAt: Date.now(),
    };
    this.sessions.set(session.id, session);
    return session;
  }

  /**
   * Get an existing session by ID.
   */
  getSession(sessionId: string): DiffChatSession | undefined {
    return this.sessions.get(sessionId);
  }

  /**
   * Create a chat thread anchored to a specific hunk and line range.
   */
  createThread(
    sessionId: string,
    hunkId: string,
    lineRange: { start: number; end: number },
    initialMessage?: { author: string; body: string; isAi?: boolean },
  ): ChatThread | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    const hunk = session.diff.hunks.find((h) => h.id === hunkId);
    if (!hunk) return null;

    const now = Date.now();
    const threadId = `thread_${randomUUID().slice(0, 8)}`;

    const thread: ChatThread = {
      id: threadId,
      hunkId,
      file: session.diff.file,
      lineRange,
      messages: [],
      resolved: false,
      createdAt: now,
      updatedAt: now,
    };

    if (initialMessage) {
      const msg: ChatMessage = {
        id: `msg_${randomUUID().slice(0, 8)}`,
        threadId,
        author: initialMessage.author,
        body: initialMessage.body,
        timestamp: now,
        isAi: initialMessage.isAi ?? false,
      };
      thread.messages.push(msg);
    }

    session.threads.push(thread);

    // Create annotations for each line in the range
    for (let ln = lineRange.start; ln <= lineRange.end; ln++) {
      const annotation: LineAnnotation = {
        id: `ann_${randomUUID().slice(0, 8)}`,
        file: session.diff.file,
        hunkId,
        anchorLine: ln,
        threadId,
      };
      session.annotations.push(annotation);
    }

    return thread;
  }

  /**
   * Add a message to an existing thread.
   */
  addMessage(
    sessionId: string,
    threadId: string,
    message: { author: string; body: string; isAi?: boolean; parentId?: string },
  ): ChatMessage | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    const thread = session.threads.find((t) => t.id === threadId);
    if (!thread) return null;

    const msg: ChatMessage = {
      id: `msg_${randomUUID().slice(0, 8)}`,
      threadId,
      author: message.author,
      body: message.body,
      timestamp: Date.now(),
      isAi: message.isAi ?? false,
      parentId: message.parentId,
    };

    thread.messages.push(msg);
    thread.updatedAt = Date.now();
    return msg;
  }

  /**
   * Resolve (close) a thread.
   */
  resolveThread(sessionId: string, threadId: string): boolean {
    const session = this.sessions.get(sessionId);
    if (!session) return false;

    const thread = session.threads.find((t) => t.id === threadId);
    if (!thread) return false;

    thread.resolved = true;
    thread.updatedAt = Date.now();
    return true;
  }

  /**
   * Get all threads for a specific hunk.
   */
  getThreadsForHunk(sessionId: string, hunkId: string): ChatThread[] {
    const session = this.sessions.get(sessionId);
    if (!session) return [];
    return session.threads.filter((t) => t.hunkId === hunkId);
  }

  /**
   * Get all annotations for a specific file and line.
   */
  getAnnotationsForLine(sessionId: string, file: string, line: number): LineAnnotation[] {
    const session = this.sessions.get(sessionId);
    if (!session) return [];
    return session.annotations.filter(
      (a) => a.file === file && a.anchorLine === line,
    );
  }

  /**
   * Get all annotations for an entire file.
   */
  getAnnotationsForFile(sessionId: string, file: string): LineAnnotation[] {
    const session = this.sessions.get(sessionId);
    if (!session) return [];
    return session.annotations
      .filter((a) => a.file === file)
      .sort((a, b) => a.anchorLine - b.anchorLine);
  }

  /**
   * Build inline reply rendering data for a thread.
   * Returns structured data suitable for rendering in a diff view.
   */
  buildInlineReplies(sessionId: string, hunkId: string): InlineReply[] {
    const session = this.sessions.get(sessionId);
    if (!session) return [];

    const threads = session.threads.filter((t) => t.hunkId === hunkId && !t.resolved);
    const replies: InlineReply[] = [];

    for (const thread of threads) {
      const lastMsg = thread.messages[thread.messages.length - 1];
      const replyText = lastMsg
        ? `${lastMsg.author}: ${lastMsg.body}`
        : '(empty thread)';

      const renderedHtml = buildReplyHtml(thread);

      replies.push({
        threadId: thread.id,
        hunkId,
        file: thread.file,
        anchorLine: thread.lineRange.start,
        replyText,
        renderedHtml,
      });
    }

    return replies;
  }

  /**
   * Get a summary of all unresolved threads across the session.
   */
  getUnresolvedCount(sessionId: string): number {
    const session = this.sessions.get(sessionId);
    if (!session) return 0;
    return session.threads.filter((t) => !t.resolved).length;
  }

  /**
   * Delete a session.
   */
  deleteSession(sessionId: string): boolean {
    return this.sessions.delete(sessionId);
  }
}

// ──────────────────────────────────────────────
// Inline Reply HTML Renderer
// ──────────────────────────────────────────────

function buildReplyHtml(thread: ChatThread): string {
  const msgCount = thread.messages.length;
  const parts: string[] = [
    `<div class="diff-chat-thread" data-thread-id="${thread.id}" data-hunk-id="${thread.hunkId}">`,
    `  <div class="diff-chat-thread-header">`,
    `    <span class="thread-line-range">Lines ${thread.lineRange.start}–${thread.lineRange.end}</span>`,
    `    <span class="thread-status ${thread.resolved ? 'resolved' : 'active'}">${thread.resolved ? '✓ Resolved' : '● Active'}</span>`,
    `    <span class="thread-count">${msgCount} message${msgCount !== 1 ? 's' : ''}</span>`,
    `  </div>`,
  ];

  for (const msg of thread.messages) {
    const role = msg.isAi ? 'ai' : 'user';
    parts.push(
      `  <div class="diff-chat-msg msg-${role}" data-msg-id="${msg.id}">`,
      `    <span class="msg-author">${escapeHtml(msg.author)}</span>`,
      `    <span class="msg-time">${new Date(msg.timestamp).toLocaleTimeString()}</span>`,
      `    <div class="msg-body">${escapeHtml(msg.body)}</div>`,
      `  </div>`,
    );
  }

  parts.push('</div>');
  return parts.join('\n');
}

function escapeHtml(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

