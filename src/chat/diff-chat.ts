/**
 * Build a unified diff string from two file content strings (simple implementation).
 */
export function generateUnifiedDiff(
  oldContent: string,
  newContent: string,
  filePath: string,
  contextLines: number = 3,
): string {
  const oldLines = oldContent.split('\n');
  const newLines = newContent.split('\n');

  // Find differing line ranges using a simple LCS-free approach
  const changes = computeLineChanges(oldLines, newLines);

  if (changes.length === 0) return '';

  const parts: string[] = [
    `diff --git a/${filePath} b/${filePath}`,
    `--- a/${filePath}`,
    `+++ b/${filePath}`,
  ];

  for (const change of changes) {
    const oldStart = change.oldStart;
    const oldEnd = change.oldStart + change.oldCount;
    const newStart = change.newStart;
    const newEnd = change.newStart + change.newCount;

    parts.push(`@@ -${oldStart},${oldEnd - oldStart} +${newStart},${newEnd - newStart} @@`);

    for (let i = change.oldStart; i < oldEnd; i++) {
      parts.push(`-${oldLines[i - 1]}`);
    }
    for (let i = change.newStart; i < newEnd; i++) {
      parts.push(`+${newLines[i - 1]}`);
    }
  }

  return parts.join('\n');
}

interface LineChange {
  oldStart: number; // 1-based
  oldCount: number;
  newStart: number; // 1-based
  newCount: number;
}

function computeLineChanges(oldLines: string[], newLines: string[]): LineChange[] {
  const changes: LineChange[] = [];
  const maxLen = Math.max(oldLines.length, newLines.length);
  let i = 0;

  while (i < maxLen) {
    const oldLine = i < oldLines.length ? oldLines[i] : undefined;
    const newLine = i < newLines.length ? newLines[i] : undefined;

    if (oldLine !== newLine) {
      // Start of a change
      let oldCount = 0;
      let newCount = 0;
      const start = i;

      // Collect removed lines (present in old, not in new at current position)
      while (i + oldCount < oldLines.length) {
        const ol = oldLines[i + oldCount];
        const nl = i + oldCount < newLines.length ? newLines[i + oldCount] : undefined;
        if (ol !== nl) {
          oldCount++;
        } else {
          break;
        }
      }

      // Collect added lines
      while (i + newCount < newLines.length) {
        const nl = newLines[i + newCount];
        const ol = i + newCount < oldLines.length ? oldLines[i + newCount] : undefined;
        if (nl !== ol) {
          newCount++;
        } else {
          break;
        }
      }

      changes.push({
        oldStart: start + 1,
        oldCount: oldCount,
        newStart: start + 1,
        newCount: newCount,
      });

      i += Math.max(oldCount, newCount);
    } else {
      i++;
    }
  }

  return changes;
}
