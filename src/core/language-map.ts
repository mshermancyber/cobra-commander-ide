const FILENAME_MAP: Record<string, string> = {
  'Makefile': 'makefile',
  'Dockerfile': 'dockerfile',
  'Jenkinsfile': 'groovy',
  'Gemfile': 'ruby',
  'Rakefile': 'ruby',
  'Vagrantfile': 'ruby',
  '.gitignore': 'ignore',
  '.dockerignore': 'ignore',
  '.editorconfig': 'editorconfig',
  '.env': 'dotenv',
};

export function getLanguageId(filePath: string): string | undefined {
  const name = basename(filePath);
  if (FILENAME_MAP[name]) return FILENAME_MAP[name];

  const ext = extname(filePath).toLowerCase();
  return LANGUAGE_EXTENSIONS[ext];
}

export function getSupportedExtensions(): string[] {
  return Object.keys(LANGUAGE_EXTENSIONS);
}

export function getLanguageExtensions(): Record<string, string> {
  return { ...LANGUAGE_EXTENSIONS };
}
